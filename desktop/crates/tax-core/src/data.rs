//! Case data is embedded at compile time so the desktop binary is self-contained.

use crate::model::{Dataset, Meta, TaxRateDef};

const DOCUMENTS_JSON: &str = include_str!("../../../../data/documents.json");
const LEDGER_JSON: &str = include_str!("../../../../data/ledger.json");
const TABLES_JSON: &str = include_str!("../../../../data/tables.json");
const DICT_JSON: &str = include_str!("../../../../data/dict.json");
const POLICIES_JSON: &str = include_str!("../../../../data/policies.json");
const ACCEPTANCE_JSON: &str = include_str!("../../../../data/_acceptance_report.json");
const QUALITY_JSON: &str = include_str!("../../../../data/_data_quality.json");

fn parse<T: serde::de::DeserializeOwned>(raw: &str, label: &str) -> T {
    serde_json::from_str(raw).unwrap_or_else(|e| panic!("embedded {label} JSON is invalid: {e}"))
}

/// Load and cache the embedded dataset for the lifetime of the process.
pub fn dataset() -> &'static Dataset {
    use std::sync::OnceLock;
    static DATA: OnceLock<Dataset> = OnceLock::new();
    DATA.get_or_init(|| {
        let mut ds: Dataset = Dataset {
            documents: parse(DOCUMENTS_JSON, "documents"),
            ledger: parse(LEDGER_JSON, "ledger"),
            tables: parse(TABLES_JSON, "tables"),
            dict: parse(DICT_JSON, "dict"),
            policies: parse(POLICIES_JSON, "policies"),
            acceptance: Some(parse(ACCEPTANCE_JSON, "acceptance report")),
            data_quality: Some(parse(QUALITY_JSON, "data quality")),
            ..Default::default()
        };
        // The meta object is generated by tools/build.py and not persisted as its own file.
        ds.meta = Meta {
            case: "华衡智造 2025.12".into(),
            period: "2025 年 12 月".into(),
            company: "华衡智造集团股份有限公司".into(),
            self_tax_no: "91440300MA5H8K2X3Q".into(),
            project: "P1-01 发票开具".into(),
            dataset: "P1-01-发票开具-勾选数据集".into(),
            doc_count: ds.documents.len() as i64,
            table_count: 4,
            case_count: ds.tables.cases.len() as i64,
            generated_at: "2026-11-14T09:52:32Z".into(),
        };
        ds
    })
}

/// Runtime rule tables, injected from dict.json (with built-in fallbacks).
#[derive(Debug, Clone)]
pub struct Rules {
    pub tax_rates: Vec<TaxRateDef>,
    pub scope: Vec<crate::model::ScopeItem>,
    pub customers: Vec<crate::model::CustomerDef>,
}

impl Rules {
    pub fn from_dataset(ds: &Dataset) -> Self {
        let mut tax_rates = ds.dict.tax_rates.clone();
        if tax_rates.is_empty() {
            tax_rates = vec![
                TaxRateDef {
                    rate: "13%".into(),
                    scope: "销售货物".into(),
                    ..Default::default()
                },
                TaxRateDef {
                    rate: "9%".into(),
                    scope: "交通运输、建筑等".into(),
                    ..Default::default()
                },
                TaxRateDef {
                    rate: "6%".into(),
                    scope: "现代服务".into(),
                    ..Default::default()
                },
                TaxRateDef {
                    rate: "0%".into(),
                    scope: "出口货物".into(),
                    ..Default::default()
                },
                TaxRateDef {
                    rate: "5%".into(),
                    scope: "简易计税".into(),
                    ..Default::default()
                },
            ];
        }
        Self {
            tax_rates,
            scope: ds.dict.scope.clone(),
            customers: ds.dict.customers.clone(),
        }
    }

    pub fn rate_known(&self, rate: f64) -> bool {
        self.tax_rates.iter().any(|t| {
            crate::money::parse_rate(&t.rate)
                .map(|r| (r - rate).abs() < 1e-9)
                .unwrap_or(false)
        })
    }

    pub fn scope_hit(&self, product: &str) -> Option<crate::model::ScopeItem> {
        self.scope.iter().find(|s| s.product == product).cloned()
    }

    pub fn customer(&self, name: &str) -> Option<crate::model::CustomerDef> {
        self.customers.iter().find(|c| c.name == name).cloned()
    }
}
